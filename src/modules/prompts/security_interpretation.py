"""Role-neutral principles for interpreting security evidence and future checks."""

SECURITY_INTERPRETATION = (
    "Keep observed facts, assumptions and unresolved prerequisites explicit. Identify expected legitimate "
    "behavior and the suspected security consequence. What observation would distinguish that consequence "
    "from legitimate behavior? Use a baseline, a controlled variation and the evidence needed to tell them "
    "apart. For each claimed security consequence, identify both a supporting observation and an "
    "observation of the same probe that would refute it under the intended policy. A successful baseline "
    "or an unrelated invalid-input control cannot substitute for that refuting observation. The "
    "distinction may be expressed anywhere in the plan; no particular wording or field placement is "
    "required. A timeout, reset or I/O error alone is inconclusive about policy enforcement. Distinguish "
    "evidence that the probe reached the relevant enforcement boundary and was denied from transport "
    "or resource failure; do not label those failures policy-compliant denial. "
    "An ordinary intermediate effect is not the claimed consequence. These are planned "
    "observations, not a requirement to execute future tests or obtain results now. Future identity "
    "comparisons must agree with declared "
    "authentication requirements, even when credentials are not yet available. Successful execution or a "
    "different response establishes only what was observed. Establish "
    "what the assigned operation normally permits, its relevant processing boundary and unresolved policy. "
    "Preserve this context in source references, observed_basis and preconditions. Instruction following, "
    "reflection, record selection and URL fetching must be assessed against that intended boundary. "
    "Following an instruction or fetching a supplied URL alone does not establish a policy violation. "
    "Establish relevant policy from documentation, configuration or independently known authorized and denied "
    "baselines. Unknown implementation details can become future checks when observed behavior motivates "
    "a conditional proposal. Observed client input and data flow can provide that basis without confirmed "
    "server handling. Preserve uncertainty until the distinguishing evidence is available. "
)
